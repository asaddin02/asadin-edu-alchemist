// Textbook references. Content cites sections of OpenStax books (CC BY 4.0) by a short code:
//   '4-2-classifying-chemical-reactions'        → Chemistry 2e, section 4.2
//   'oc:11-2-the-sn2-reaction'                   → Organic Chemistry, section 11.2
//   'bio:3-4-proteins'                           → Biology 2e, section 3.4
// scripts/check-data.mjs accepts only sections listed in the books' own tables of contents
// (scripts/data/openstax-sections.json), so a reference can never point at a page that does not exist.
// Labels use each section's official title (js/data/sectionTitles.js, generated by `npm run build`).
import { SECTION_TITLES } from './sectionTitles.js';

export const BOOKS = {
  chem: { slug: 'chemistry-2e', title: 'OpenStax Chemistry 2e' },
  oc: { slug: 'organic-chemistry', title: 'OpenStax Organic Chemistry' },
  bio: { slug: 'biology-2e', title: 'OpenStax Biology 2e' },
};

/** '4-2-classifying-chemical-reactions' → { book, slug, url, label: 'OpenStax Chemistry 2e · 4.2 Classifying Chemical Reactions' }. */
export function reference(code) {
  const [prefix, rest] = String(code).includes(':') ? String(code).split(':') : ['chem', String(code)];
  const book = BOOKS[prefix];
  if (!book || !rest) return null;
  const m = rest.match(/^(\d+)-(\d+)-(.+)$/);
  const fallback = m ? `${m[1]}.${m[2]} ${m[3].replace(/-/g, ' ')}` : rest.replace(/-/g, ' ');
  const title = SECTION_TITLES[code] || `${fallback.charAt(0).toUpperCase()}${fallback.slice(1)}`;
  return {
    book: book.slug,
    slug: rest,
    url: `https://openstax.org/books/${book.slug}/pages/${rest}`,
    label: `${book.title} · ${title}`,
  };
}
